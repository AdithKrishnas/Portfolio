// LocalStorage Persistence Key - Bumped to v8 (Animus Suite Synchronization)
const STORAGE_KEY = "adith_portfolio_animus_v8";

function loadProjects() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      // Validate that saved array contains the full suite projects
      const hasSuiteData = Array.isArray(parsed) && parsed.some(p => Array.isArray(p.suite) && p.suite.length > 0);
      if (hasSuiteData && parsed.length >= DEFAULT_PROJECTS_DATA.length) {
        return parsed;
      }
    }
  } catch (e) {
    console.warn("Could not read from localStorage, using defaults", e);
  }
  // Store default dataset to localStorage
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(DEFAULT_PROJECTS_DATA));
  } catch (e) {}
  return [...DEFAULT_PROJECTS_DATA];
}

let PROJECTS_DATA = loadProjects();

function getProjectsByCategory(category) {
  if (!category || category === "all") return PROJECTS_DATA;
  return PROJECTS_DATA.filter(p => p.category === category);
}

function getProjectsBySuite(suite) {
  if (!suite || suite === "all") {
    return PROJECTS_DATA.filter(p => p.category === "graphic-design" || p.category === "posters" || p.category === "brochures" || (p.suite && p.suite.length > 0));
  }
  const s = suite.toLowerCase();
  const results = PROJECTS_DATA.filter(p => {
    if (Array.isArray(p.suite) && p.suite.some(x => x.toLowerCase().includes(s))) return true;
    if (typeof p.suite === "string" && p.suite.toLowerCase().includes(s)) return true;
    if (Array.isArray(p.tools) && p.tools.some(t => t.toLowerCase().includes(s))) return true;
    if (Array.isArray(p.tags) && p.tags.some(t => t.toLowerCase().includes(s))) return true;
    return false;
  });

  // Safe fallback: never let an active portal render empty
  if (results.length === 0) {
    return PROJECTS_DATA.filter(p => p.category === "graphic-design" || p.category === "posters" || p.category === "brochures");
  }
  return results;
}

function getProjectById(id) {
  return PROJECTS_DATA.find(p => p.id === id);
}

function getFeaturedShowcaseProjects() {
  return PROJECTS_DATA.filter(p => p.featuredInShowcase);
}

function saveProjectsToStorage(newProjectsArray) {
  PROJECTS_DATA = newProjectsArray;
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(PROJECTS_DATA));
  } catch (e) {
    console.error("Failed to save to localStorage", e);
  }
  window.dispatchEvent(new CustomEvent("projectsUpdated"));
}

function addProject(projectObj) {
  PROJECTS_DATA.unshift(projectObj);
  saveProjectsToStorage(PROJECTS_DATA);
}

function updateProject(projectId, updatedObj) {
  const index = PROJECTS_DATA.findIndex(p => p.id === projectId);
  if (index !== -1) {
    PROJECTS_DATA[index] = { ...PROJECTS_DATA[index], ...updatedObj };
    saveProjectsToStorage(PROJECTS_DATA);
    return true;
  }
  return false;
}

function deleteProject(projectId) {
  PROJECTS_DATA = PROJECTS_DATA.filter(p => p.id !== projectId);
  saveProjectsToStorage(PROJECTS_DATA);
}

function resetProjectsToDefaults() {
  PROJECTS_DATA = [...DEFAULT_PROJECTS_DATA];
  localStorage.removeItem(STORAGE_KEY);
  window.dispatchEvent(new CustomEvent("projectsUpdated"));
}
